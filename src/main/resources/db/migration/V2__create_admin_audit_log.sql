-- Who did what to which account. Written whenever an admin locks, unlocks, grants or revokes admin.
-- The emails are copied in, so the log stays readable even if an account is changed later.
-- admin_user_id is empty when the change was made by the start-up bootstrap (no person).

create table admin_audit_log (
    id            bigint generated by default as identity primary key,
    admin_user_id bigint,
    admin_email   varchar(255) not null,
    action        varchar(255) not null,
    target_user_id bigint not null,
    target_email  varchar(255) not null,
    created_at    timestamp(6) with time zone not null
);

create index idx_admin_audit_log_created_at on admin_audit_log (created_at);
