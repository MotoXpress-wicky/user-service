-- user_db. Same shape that Hibernate made with ddl-auto: update before, so a new
-- database and an old one match. Hibernate only checks it now (ddl-auto: validate).

create table users (
    id            bigint generated by default as identity primary key,
    name          varchar(255),
    email         varchar(255) not null unique,
    password      varchar(255),
    roles         varchar(255) array not null,
    auth_provider varchar(255) not null check (auth_provider in ('LOCAL', 'GOOGLE')),
    locked        boolean not null
);

create table refresh_tokens (
    id         bigint generated by default as identity primary key,
    token_hash varchar(64) not null unique,
    user_id    bigint not null references users (id),
    expires_at timestamp(6) with time zone not null,
    revoked_at timestamp(6) with time zone
);

create index idx_refresh_token_hash on refresh_tokens (token_hash);

create table password_reset_token (
    id         bigint generated by default as identity primary key,
    token_hash varchar(64) not null unique,
    user_id    bigint not null references users (id),
    expires_at timestamp(6) with time zone not null,
    used_at    timestamp(6) with time zone,
    created_at timestamp(6) with time zone
);

create index idx_password_reset_token_hash on password_reset_token (token_hash);
